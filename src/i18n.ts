import i18n from 'i18next';
import { initReactI18next } from 'react-i18next';
import LanguageDetector from 'i18next-browser-languagedetector';

import ar from './locales/ar.json';
import en from './locales/en.json';

i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources: {
      ar: { translation: ar },
      en: { translation: en },
    },
    fallbackLng: 'ar',
    supportedLngs: ['ar', 'en'],
    detection: {
      order: ['localStorage', 'navigator'],
      caches: ['localStorage'],
    },
    interpolation: {
      escapeValue: false,
    },
  });

// Automatically update HTML document direction and lang attribute whenever language changes
const updateDocumentAttributes = (lng: string) => {
  if (typeof document !== 'undefined') {
    const isRtl = lng.startsWith('ar');
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
    document.documentElement.lang = isRtl ? 'ar' : 'en';
  }
};

updateDocumentAttributes(i18n.language || 'ar');

i18n.on('languageChanged', (lng) => {
  updateDocumentAttributes(lng);
});

export default i18n;
